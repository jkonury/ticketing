#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

set -a
source .env
set +a
export TICKETING_PAYMENT_POSTGRES_DB="${TICKETING_PAYMENT_POSTGRES_DB:-payment_db}"
export TICKETING_PAYMENT_POSTGRES_USER="${TICKETING_PAYMENT_POSTGRES_USER:-payment}"
export TICKETING_SETTLEMENT_POSTGRES_DB="${TICKETING_SETTLEMENT_POSTGRES_DB:-settlement_db}"
export TICKETING_SETTLEMENT_POSTGRES_USER="${TICKETING_SETTLEMENT_POSTGRES_USER:-settlement}"
export TICKETING_SETTLEMENT_POSTGRES_PASSWORD="${TICKETING_SETTLEMENT_POSTGRES_PASSWORD:?정산 DB 비밀번호를 설정하세요}"

docker compose exec -T \
  -e TICKETING_POSTGRES_DB -e TICKETING_PAYMENT_POSTGRES_DB -e TICKETING_PAYMENT_POSTGRES_USER \
  -e TICKETING_SETTLEMENT_POSTGRES_DB -e TICKETING_SETTLEMENT_POSTGRES_USER -e TICKETING_SETTLEMENT_POSTGRES_PASSWORD \
  postgres psql -X --no-password --set=ON_ERROR_STOP=1 \
  --username "$TICKETING_POSTGRES_USER" --dbname "$TICKETING_POSTGRES_DB" \
  < deploy/postgres/init/20-settlement-db.sql
